const goldenDocument = `# Generated by autodeploy internal/runtime/traefik. Do not edit by hand;
# this file is replaced atomically on every activation.
# environment: env01ABCxyz
# route_revision: 7
http:
  routers:
    "autodeploy-router-env01ABCxyz":
      rule: "Host(` + "`" + `app.example.com` + "`" + `)"
      entryPoints:
        - "websecure"
      service: "autodeploy-svc-env01ABCxyz-rel01ABCxyz-fen01ABCxyz"
      tls:
        certResolver: "letsencrypt"
  services:
    "autodeploy-svc-env01ABCxyz-rel01ABCxyz-fen01ABCxyz":
      loadBalancer:
        servers:
          - url: "http://autodeploy-rt-rti01ABCxyz:8080"
`

func TestRenderGoldenBytes(t *testing.T) {
	doc, digest, err := Render(validRoute())
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if string(doc) != goldenDocument {
		t.Fatalf("rendered document mismatch.\n--- got ---\n%s\n--- want ---\n%s", doc, goldenDocument)
	}
	sum := sha256.Sum256(doc)
	want := "sha256:" + hex.EncodeToString(sum[:])
	if digest != want {
		t.Fatalf("digest = %s, want %s", digest, want)
	}
}

func TestRenderDeterministic(t *testing.T) {
	r := validRoute()
	first, firstDigest, err := Render(r)
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	for i := 0; i < 20; i++ {
		// Reconstruct r from scratch each iteration (not reused by
		// pointer) so this also proves determinism is a property of the
		// value, not of some accidental shared state between calls.
		again := validRoute()
		doc, digest, err := Render(again)
		if err != nil {
			t.Fatalf("Render iteration %d: %v", i, err)
		}
		if string(doc) != string(first) {
			t.Fatalf("iteration %d: rendered bytes differ", i)
		}
		if digest != firstDigest {
			t.Fatalf("iteration %d: digest differs: %s vs %s", i, digest, firstDigest)
		}
	}
}

func TestRenderDigestChangesPerField(t *testing.T) {
	base := validRoute()
	_, baseDigest, err := Render(base)
	if err != nil {
		t.Fatalf("Render base: %v", err)
	}

	mutations := map[string]func(*EnvironmentRoute){
		"RouteRevision":    func(r *EnvironmentRoute) { r.RouteRevision++ },
		"Hostname":         func(r *EnvironmentRoute) { r.Hostname = "other.example.com" },
		"EntrypointName":   func(r *EnvironmentRoute) { r.EntrypointName = "web" },
		"CertResolverName": func(r *EnvironmentRoute) { r.CertResolverName = "otherresolver" },
		"BackendRuntimeInstanceID": func(r *EnvironmentRoute) {
			r.BackendRuntimeInstanceID = "rti99ZZZxyz"
		},
		"BackendPort":   func(r *EnvironmentRoute) { r.BackendPort = 9090 },
		"BackendScheme": func(r *EnvironmentRoute) { r.BackendScheme = "https" },
		"ReleaseID":     func(r *EnvironmentRoute) { r.ReleaseID = "rel99ZZZxyz" },
		"FenceID":       func(r *EnvironmentRoute) { r.FenceID = "fen99ZZZxyz" },
		"EnvironmentID": func(r *EnvironmentRoute) { r.EnvironmentID = "env99ZZZxyz" },
	}

	seen := map[string]bool{baseDigest: true}
	for name, mutate := range mutations {
		r := validRoute()
		mutate(&r)
		_, digest, err := Render(r)
		if err != nil {
			t.Fatalf("field %s: Render: %v", name, err)
		}
		if digest == baseDigest {
			t.Fatalf("field %s: digest did not change from base", name)
		}
		if seen[digest] {
			t.Fatalf("field %s: digest collided with a previously seen mutation", name)
		}
		seen[digest] = true
	}
}

func TestQuoteYAMLStringEscapesEveryDangerousByte(t *testing.T) {
	cases := []struct {
		name  string
		input string
		want  string
	}{
		{"backslash", `a\b`, `"a\\b"`},
		{"doublequote", `a"b`, `"a\"b"`},
		{"newline", "a\nb", `"a\nb"`},
		{"carriagereturn", "a\rb", `"a\rb"`},
		{"tab", "a\tb", `"a\tb"`},
		{"nul", "a\x00b", `"a\x00b"`},
		{"backtick", "a`b", "\"a`b\""},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := quoteYAMLString(tc.input)
			if err != nil {
				t.Fatalf("quoteYAMLString(%q) returned error: %v", tc.input, err)
			}
			if got != tc.want {
				t.Fatalf("quoteYAMLString(%q) = %s, want %s", tc.input, got, tc.want)
			}
		})
	}
}

// TestQuoteYAMLStringRejectsNonASCII proves the ASCII-only precondition
// review found missing: every byte 0x80 or above is rejected outright,
// including well-formed multi-byte UTF-8 sequences and specific
// YAML-line-break code points (NEL, LINE SEPARATOR, PARAGRAPH SEPARATOR)
// that a real YAML parser would otherwise reinterpret as whitespace inside
// a double-quoted scalar -- see ErrNonASCIIValue's doc comment for the
// concrete PyYAML/yaml.v3 behavior this guards against.
func TestQuoteYAMLStringRejectsNonASCII(t *testing.T) {
	cases := []struct {
		name  string
		input string
	}{
		// Every input below is built from explicit byte escapes (never a
		// literal non-ASCII source character), so the bytes under test are
		// unambiguous regardless of this file's own source encoding.
		{"NEL", "a" + "\xc2\x85" + "b"},                     // U+0085
		{"line-separator", "a" + "\xe2\x80\xa8" + "b"},      // U+2028
		{"paragraph-separator", "a" + "\xe2\x80\xa9" + "b"}, // U+2029
		{"BOM", "a" + "\xef\xbb\xbf" + "b"},                 // U+FEFF
		{"raw-0x80", "a\x80b"},
		{"raw-0xFF", "a\xffb"},
		{"valid-multibyte-rune", "caf" + "\xc3\xa9"}, // 'e-acute', a well-formed 2-byte UTF-8 rune
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := quoteYAMLString(tc.input)
			if !errors.Is(err, ErrNonASCIIValue) {
				t.Fatalf("quoteYAMLString(%q) error = %v, want ErrNonASCIIValue", tc.input, err)
			}
		})
	}
}

// TestRenderDocumentPropagatesNonASCIIRejection proves renderDocument
// itself (not just the quoteYAMLString primitive) fails closed and
// produces no partial document when any one field is non-ASCII -- calling
// renderDocument directly, bypassing EnvironmentRoute.validate, since
// validate's own charset restrictions mean no value that reaches
// renderDocument through the public Render path can ever be non-ASCII
// today (see ErrNonASCIIValue's doc comment).
func TestRenderDocumentPropagatesNonASCIIRejection(t *testing.T) {
	r := validRoute()
	doc, err := renderDocument(r, "router\u0085name", "svc", "http://backend:8080")
	if !errors.Is(err, ErrNonASCIIValue) {
		t.Fatalf("renderDocument error = %v, want ErrNonASCIIValue", err)
	}
	if doc != nil {
		t.Fatalf("expected nil document on error, got %q", doc)
	}
}

// TestRenderFailsClosedOnNonASCII proves the same guarantee at the public
// Render entry point via the field renderDocument itself cannot validate
// away (r.Hostname's charset is already ASCII-only by construction, so
// this reaches into renderDocument's router-name argument indirectly by
// constructing a route whose EnvironmentID -- which both validate() and
// routerName derive the router name from -- would need to be non-ASCII;
// since identifierPattern is itself ASCII-only, validate() rejects that
// first with ErrInvalidRoute, which is the correct and only reachable
// outcome through the public API. This test documents that reachability
// boundary explicitly rather than asserting an unreachable path.
func TestRenderFailsClosedOnNonASCII(t *testing.T) {
	r := validRoute()
	r.EnvironmentID = "env\u0085not-ascii"
	if _, _, err := Render(r); !errors.Is(err, ErrInvalidRoute) {
		t.Fatalf("expected ErrInvalidRoute (rejected before reaching quoteYAMLString), got %v", err)
	}
}

// TestQuoteYAMLStringInjectionCannotAddKeysOrEscapeScalar feeds the quoting
// primitive strings shaped like a YAML/Traefik-rule injection attempt --
// bypassing EnvironmentRoute.validate entirely -- and proves the quoted
// output never contains an unescaped double-quote or raw newline: the two
// bytes that could otherwise terminate the surrounding YAML scalar early
// and let injected content be reinterpreted as new document structure.
func TestQuoteYAMLStringInjectionCannotAddKeysOrEscapeScalar(t *testing.T) {
	attacks := []string{
		"evil\"\n  extraKey: true\n  rule: \"Host(`x",
		"a\"\ntls:\n  certResolver: attacker",
		"\r\nrouters:\n  evil:\n    rule: \"Host(`x`)\"",
	}
	for _, a := range attacks {
		quoted, err := quoteYAMLString(a)
		if err != nil {
			t.Fatalf("quoteYAMLString(%q) returned error: %v", a, err)
		}
		if !strings.HasPrefix(quoted, `"`) || !strings.HasSuffix(quoted, `"`) {
			t.Fatalf("quoted value not properly wrapped: %q", quoted)
		}
		inner := quoted[1 : len(quoted)-1]
		if strings.ContainsRune(inner, '\n') || strings.ContainsRune(inner, '\r') {
			t.Fatalf("quoted value contains a raw newline/carriage-return: %q", quoted)
		}
		// Every '"' inside inner must be immediately preceded by a '\'
		// that is not itself escaped -- i.e. every quote is escaped.
		for i := 0; i < len(inner); i++ {
			if inner[i] == '"' {
				if i == 0 || inner[i-1] != '\\' {
					t.Fatalf("unescaped double-quote at byte %d in %q", i, quoted)
				}
			}
		}
	}
}

// TestRenderInjectionAttemptsCannotAlterRuleOrAddKeys proves the full
// render pipeline end to end: even a hostname string that LOOKS like it
// should terminate the rule and inject new YAML keys is rejected by
// validate before renderDocument ever runs, so Render never has the chance
// to produce a document with extra keys.
func TestRenderInjectionAttemptsCannotAlterRuleOrAddKeys(t *testing.T) {
	attacks := []string{
		"a.com`)\n  entryPoints: [evil]\n  rule: Host(`b.com",
		"a.com\"\ntls:\n  certResolver: attacker\nrule: \"Host(`b.com",
	}
	for _, a := range attacks {
		r := validRoute()
		r.Hostname = a
		if _, _, err := Render(r); err == nil {
			t.Fatalf("expected Render to reject injection-shaped hostname %q", a)
		}
	}
}
